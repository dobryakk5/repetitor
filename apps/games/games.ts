export type GameType = 'riddle' | 'puzzle' | 'quiz' | 'game' | 'crossword' | 'charade';

export interface Game {
  id: string;
  title: string;
  type: GameType;
  section: 'phonetics' | 'morphology' | 'lexics';
  sectionTitle: string;
  topic: string;
  description: string;
  content: GameContent;
  source: string; // page reference
}

export interface GameContent {
  instructions?: string;
  items?: Item[];
  charades?: Charade[];
  riddles?: Riddle[];
  crossword?: CrosswordData;
  quiz?: QuizQuestion[];
  text?: string;
}

export interface Item {
  question: string;
  answer?: string;
  hint?: string;
}

export interface Charade {
  verse: string;
  answer: string;
}

export interface Riddle {
  text: string;
  answer: string;
}

export interface CrosswordData {
  across: CrosswordClue[];
  down: CrosswordClue[];
  grid?: string[][];
}

export interface CrosswordClue {
  number: number;
  clue: string;
  answer: string;
  row?: number;
  col?: number;
}

export interface QuizQuestion {
  question: string;
  answer: string;
}

